function renderRecipe(dish) {
  recipeEmptyEl.classList.add("hidden");
  recipePanelEl.classList.remove("hidden");
  recipeTitleEl.textContent = dish.name;
  recipeServingsEl.textContent = "默认 2 人份";
  recipeTipsEl.textContent = dish.tips;

  recipeTagsEl.innerHTML = "";
  dish.tags.forEach((tag) => {
    const chip = document.createElement("span");
    chip.className = "recipe-tag";
    chip.textContent = tag;
    recipeTagsEl.appendChild(chip);
  });

  ingredientsListEl.innerHTML = "";
  dish.ingredients.forEach((item) => {
    const li = document.createElement("li");
    li.textContent = item;
    ingredientsListEl.appendChild(li);
  });

  stepsListEl.innerHTML = "";
  const renderedSteps = detailedStepsByDish[dish.name] || dish.steps.map((step) => enrichStepText(step, dish));
  renderedSteps.forEach((step) => {
    const li = document.createElement("li");
    li.textContent = step;
    stepsListEl.appendChild(li);
  });

  const links = videoLinksByDish[dish.name] || [];
  recipeVideoLinksEl.innerHTML = "";

  if (links.length === 0) {
    recipeVideoEmptyEl.classList.remove("hidden");
  } else {
    recipeVideoEmptyEl.classList.add("hidden");
    links.forEach((item) => {
      const anchor = document.createElement("a");
      anchor.className = "video-link";
      anchor.href = item.url;
      anchor.target = "_blank";
      anchor.rel = "noreferrer";
      anchor.textContent = item.label;
      recipeVideoLinksEl.appendChild(anchor);
    });

    const copyButton = document.createElement("button");
    copyButton.className = "video-link is-copy";
    copyButton.type = "button";
    copyButton.textContent = "复制搜索词";
    copyButton.addEventListener("click", async () => {
      const keyword = `${dish.name} 做法`;
      try {
        await navigator.clipboard.writeText(keyword);
        copyButton.textContent = "已复制";
        window.setTimeout(() => {
          copyButton.textContent = "复制搜索词";
        }, 1200);
      } catch {
        copyButton.textContent = "复制失败";
        window.setTimeout(() => {
          copyButton.textContent = "复制搜索词";
        }, 1200);
      }
    });
    recipeVideoLinksEl.appendChild(copyButton);
  }
}

function resetRecipePanel() {
  recipePanelEl.classList.add("hidden");
  recipeEmptyEl.classList.remove("hidden");
  recipeTitleEl.textContent = "";
  recipeTagsEl.innerHTML = "";
  ingredientsListEl.innerHTML = "";
  stepsListEl.innerHTML = "";
  recipeTipsEl.textContent = "";
  recipeVideoLinksEl.innerHTML = "";
  recipeVideoEmptyEl.classList.remove("hidden");
  recipeServingsEl.textContent = "默认 2 人份";
}

function stopRolling(finalDish) {
  if (rollingTimer) {
    clearInterval(rollingTimer);
    rollingTimer = null;
  }

  resultEl.classList.remove("is-rolling");

  if (!finalDish) {
    currentDish = "";
    resultEl.textContent = "当前筛选下没有可抽的菜";
    resultMetaEl.textContent = "可以切回“全部”，或关闭避开最近 3 次后再试。";
    highlightDish("");
    return;
  }

  currentDish = finalDish.name;
  resultEl.textContent = finalDish.name;
  resultMetaEl.textContent = `${finalDish.tags.join(" / ")}${avoidRecentCheckbox.checked ? " · 已避开最近 3 次" : ""}`;
  highlightDish(finalDish.name);
  renderRecipe(finalDish);

  history = [finalDish.name, ...history.filter((dish) => dish !== finalDish.name)].slice(0, MAX_HISTORY);
  saveHistory();
  renderHistory();
  updateMenuVisibility();
}

function pickDish() {
  pickBtn.disabled = true;
  rerollBtn.disabled = true;
  resultEl.classList.add("is-rolling");

  let ticks = 0;
  rollingTimer = setInterval(() => {
    const previewDish = drawDish();
    resultEl.textContent = previewDish ? previewDish.name : "当前筛选下没有可抽的菜";
    highlightDish(previewDish ? previewDish.name : "");
    ticks += 1;

    if (ticks >= 16) {
      stopRolling(drawDish());
      pickBtn.disabled = false;
      rerollBtn.disabled = false;
    }
  }, 90);
}

async function copyCurrentDish() {
  if (!currentDish) {
    resultEl.textContent = "先抽一道，再复制结果。";
    return;
  }

  try {
    await navigator.clipboard.writeText(currentDish);
    copyBtn.textContent = "已复制";
    window.setTimeout(() => {
      copyBtn.textContent = "复制结果";
    }, 1200);
  } catch {
    copyBtn.textContent = "复制失败";
    window.setTimeout(() => {
      copyBtn.textContent = "复制结果";
    }, 1200);
  }
}

function clearHistory() {
  history = [];
  saveHistory();
  renderHistory();
  updateMenuVisibility();
  currentDish = "";
  resultEl.classList.remove("is-rolling");
  resultEl.textContent = "点击下面按钮开始抽菜";
  highlightDish("");
  resetRecipePanel();
  syncResultMeta();
}

